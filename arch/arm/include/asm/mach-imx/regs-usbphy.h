/*
 * Freescale USB PHY Register Definitions
 *
 */

#ifndef __REGS_USBPHY_H__
#define __REGS_USBPHY_H__

#define USBPHY_CTRL				0x00000030
#define USBPHY_CTRL_SET				0x00000034
#define USBPHY_CTRL_CLR				0x00000038
#define USBPHY_CTRL_TOG				0x0000003C
#define USBPHY_PWD				0x00000000
#define USBPHY_TX				0x00000010
#define USBPHY_RX				0x00000020
#define USBPHY_DEBUG				0x00000050

#define USBPHY_CTRL_ENUTMILEVEL2		BIT(14)
#define USBPHY_CTRL_ENUTMILEVEL3		BIT(15)
#define USBPHY_CTRL_OTG_ID			BIT(27)
#define USBPHY_CTRL_CLKGATE			BIT(30)
#define USBPHY_CTRL_SFTRST			BIT(31)

#define USBNC_OFFSET				0x200
#define USBNC_PHYCFG2_ACAENB			BIT(4) /* otg_id detection enable */

#define USBNC_PHY_STATUS_OFFSET			0x23C
#define USBNC_PHYSTATUS_ID_DIG			BIT(4) /* otg_id status */

#define ANADIG_USB2_CHRG_DETECT_EN_B		BIT(20)
#define ANADIG_USB2_CHRG_DETECT_CHK_CHRG_B	BIT(19)

#define ANADIG_USB2_PLL_480_CTRL_BYPASS		BIT(16)
#define ANADIG_USB2_PLL_480_CTRL_ENABLE		BIT(13)
#define ANADIG_USB2_PLL_480_CTRL_POWER		BIT(12)
#define ANADIG_USB2_PLL_480_CTRL_EN_USB_CLKS	BIT(6)

#endif /* __REGS_USBPHY_H__ */
